"""Build ИНСТРУКЦИЯ.docx for end users."""

from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "ИНСТРУКЦИЯ.docx"


def add_heading(doc: Document, text: str, level: int = 1) -> None:
    doc.add_heading(text, level=level)


def add_para(doc: Document, text: str, bold: bool = False) -> None:
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold
    run.font.size = Pt(11)


def add_bullets(doc: Document, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def add_numbered(doc: Document, items: list[str]) -> None:
    for item in items:
        doc.add_paragraph(item, style="List Number")


def main() -> None:
    doc = Document()
    title = doc.add_heading("Media Monitor — инструкция для пользователя", 0)
    title.alignment = WD_ALIGN_PARAGRAPH.LEFT
    add_para(doc, "Версия программы: v4.0.0", bold=True)
    add_para(
        doc,
        "Программа ищет заданные слова и фразы на указанных сайтах СМИ "
        "и сохраняет результат в Excel-отчёт. Запуск — окно с кнопками Старт/Стоп "
        "(консольный режим: параметр --console). "
        "С версии 4.0 просмотренные страницы запоминаются в scan_cache.sqlite.",
    )

    add_heading(doc, "1. Что лежит в папке", 1)
    add_bullets(
        doc,
        [
            "media-monitor-vX.Y.Z.exe — запуск (окно; версия в имени файла)",
            "sites.txt — список сайтов для проверки",
            "words.txt — список слов и фраз для поиска",
            "settings.txt — настройки (даты, лимиты, кэш)",
            "exclude.txt — ссылки, которые не должны попадать в отчёт",
            "scan_cache.sqlite — кэш уже проверенных страниц (создаётся сам)",
            "*.example.txt — образцы файлов (можно смотреть, править не обязательно)",
            "reports\\ — папка с Excel-отчётами",
            "media-monitor_log.txt — лог работы",
            "ИНСТРУКЦИЯ.docx / ИНСТРУКЦИЯ.txt — эта инструкция",
        ],
    )
    add_para(doc, "Папку можно копировать на флешку целиком — привязки к полному пути нет.")

    add_heading(doc, "2. Быстрый старт", 1)
    add_numbered(
        doc,
        [
            "Откройте sites.txt — по одной ссылке на сайт в строке (например gubdaily.ru).",
            "Откройте words.txt — по одному слову или фразе в строке (например сбертройка).",
            "При необходимости настройте settings.txt (см. раздел 4), в т.ч. skip_seen_days и max_expand_links.",
            "Запустите media-monitor-v….exe — откроется окно. Нажмите Старт.",
            "Дождитесь окончания (или Стоп). Отчёт — в папке reports\\.",
        ],
    )

    add_heading(doc, "3. Как работает поиск", 1)
    add_bullets(
        doc,
        [
            "Регистр не важен: СберТройка и сбертройка — одно и то же.",
            "Без кавычек: тройка карта — все слова есть в статье (любой порядок).",
            "В кавычках: \"карта Виза принимается в городе\" — точная фраза подряд.",
            "Ищется текст статьи, а не меню/подвал сайта.",
            "Сайты сканируются параллельно; внутри одного сайта запросы идут по очереди.",
            "Программа раскрывает списки новостей и использует поиск сайта, чтобы найти статьи.",
        ],
    )

    add_heading(doc, "4. Настройки (settings.txt)", 1)
    add_para(
        doc,
        "При обновлении с v3 программа сама допишет новые ключи в ваш settings.txt "
        "(уже заданные значения не меняет).",
    )
    add_bullets(
        doc,
        [
            "article_date_not_later_than — дата ДО (включительно). Пусто = сегодня.",
            "article_date_not_older_than — дата НЕ СТАРШЕ. Пусто = без нижней границы.",
            "article_date_last_days — за сколько последних дней от сегодня искать; если >0, перекрывает оба параметра дат.",
            "auth_timeout_seconds — сколько секунд ждать логин/пароль при старте.",
            "max_scan_urls — максимум страниц на один сайт. 0 = без лимита.",
            "max_expand_links — сколько ссылок брать с одной страницы списка/поиска (это не фильтр по дате).",
            "skip_seen_days — не сканировать повторно URL из кэша за последние N дней (0 = выкл.).",
            "site_workers — сколько сайтов одновременно (0 = все сразу).",
            "log_verbose — 0 только статус этапов, 1 — URL и ошибки.",
            "comment_unavailable_sites — 1 закомментировать недоступный сайт в sites.txt (#).",
            "ssl_verify — 1 проверять (в exe уже есть CA Минцифры и др.), 0 — не проверять.",
        ],
    )
    add_para(
        doc,
        "Если дата статьи найдена и она вне диапазона — статья не попадёт в отчёт. "
        "Если дата не найдена — статья всё равно попадёт (ячейка даты будет пустой).",
    )

    add_heading(doc, "4a. Кэш страниц (scan_cache.sqlite)", 1)
    add_bullets(
        doc,
        [
            "Файл создаётся рядом с exe автоматически.",
            "При skip_seen_days>0 повторный прогон не качает уже проверенные URL.",
            "В полном логе: [cache] уже смотрели: URL.",
            "В строке «готово» и в итоге: кэш-пропуск N.",
            "Смена words.txt — страницы сканируются снова (другой fingerprint фраз).",
            "Сброс: удалите scan_cache.sqlite или поставьте skip_seen_days=0.",
            "Совет: первый прогон с большим max_expand_links (например 1000), потом можно 100–120.",
        ],
    )

    add_heading(doc, "5. Исключения (exclude.txt)", 1)
    add_para(
        doc,
        "Если статья находится, но в отчёт её не нужно — добавьте её полный URL "
        "(по одной ссылке в строке).",
    )

    add_heading(doc, "6. Отчёт Excel", 1)
    add_para(doc, "Файлы: reports\\media-monitor-ГГГГ-ММ-ДД_ЧЧ-ММ-СС.xlsx")
    add_bullets(
        doc,
        [
            "A — слово / фраза",
            "B — ссылка на страницу (кликабельная)",
            "C — дата выхода статьи",
            "D — название статьи",
            "E — дата/время скана",
            "F1 — версия программы (например v4.0.0)",
            "G1 — длительность генерации отчёта (например 12м 35с)",
            "В конце красным — недоступные и все #-закомментированные сайты из sites.txt.",
        ],
    )

    add_heading(doc, "7. Лог", 1)
    add_bullets(
        doc,
        [
            "Файл media-monitor_log.txt рядом с exe.",
            "Пишется полный ход работы (включая детальный лог URL и [cache]).",
            "Если лог больше 10 МБ, старая часть обрезается автоматически.",
        ],
    )

    add_heading(doc, "8. Типичные сообщения", 1)
    add_bullets(
        doc,
        [
            "[N/M] готово сайт — … стр., кэш-пропуск N, … находок — сайт закончен.",
            "[N/M] недоступен сайт — сайт недоступен (в Excel красным; строка в sites.txt с #).",
            "[N/M] остановлен сайт — прерван кнопкой Стоп.",
            "[cache] уже смотрели: URL — страница пропущена по кэшу (без HTTP).",
            "Кэш: scan_cache.sqlite (N стр.), не сканировать повторно 30 дн. — кэш включён.",
            "Итог: …, кэш-пропуск N — сколько URL не качали повторно.",
            "В верхней панели: готово N/M, находок, сколько сайтов сейчас качаются, параллельно.",
            "log_verbose=1 — показать URL, SSL, ошибки (по умолчанию скрыты в статусе).",
        ],
    )

    add_heading(doc, "8a. Кнопка Стоп", 1)
    add_para(
        doc,
        "Мягкая остановка: сеть закрывается сразу, новые страницы не берутся. "
        "Excel всё равно сохраняется с тем, что успели найти.",
    )

    add_heading(doc, "9. Советы", 1)
    add_bullets(
        doc,
        [
            "В sites.txt указывайте главную сайта или раздел новостей.",
            "Для точного поиска пишите фразу целиком в words.txt.",
            "После обновления exe ваши txt-конфиги не затираются; новые ключи settings допишутся сами.",
            "Образец настроек смотрите в settings.example.txt.",
            "Если сайт режет по частоте запросов — поставьте site_workers=8.",
            "Первый широкий прогон: max_expand_links=1000; потом, с наполненным кэшем, можно уменьшить.",
        ],
    )

    add_heading(doc, "10. Сколько времени занимает проверка", 1)
    add_para(
        doc,
        "Сайты идут параллельно, внутри сайта — по одному запросу. "
        "Время прогона близко к самому медленному сайту, а не к сумме всех.",
    )
    add_bullets(
        doc,
        [
            "1 сайт, 1–2 слова: обычно 1–5 минут.",
            "130 сайтов, 1–3 слова: часто десятки минут вместо многих часов (зависит от самых медленных).",
            "max_scan_urls ограничивает страницы на каждый сайт отдельно.",
            "skip_seen_days и scan_cache.sqlite ускоряют повторные прогоны.",
            "Медленные сайты и таймауты (до ~25 сек на страницу) удлиняют прогон.",
        ],
    )

    add_para(doc, "Текущий релиз: v4.0.0", bold=True)
    doc.save(OUT)
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
